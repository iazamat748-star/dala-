// Usage: npm i world-atlas@2 topojson-client@3 && node tools/map.js
const topo=require("world-atlas/countries-50m.json");const {feature}=require("topojson-client");
const fc=feature(topo,topo.objects.countries);
const W=900,lon0=45.5,lon1=88.5,lat0=39.2,lat1=56.2,k=Math.cos(48*Math.PI/180);
const sx=W/((lon1-lon0)*k),H=Math.round((lat1-lat0)*sx);
const P=([lo,la])=>{const x=Math.min(W+20,Math.max(-20,(lo-lon0)*k*sx)),y=Math.min(H+20,Math.max(-20,(lat1-la)*sx));return [x.toFixed(0),y.toFixed(0)];};
const path=(geom)=>{const polys=geom.type==="Polygon"?[geom.coordinates]:geom.coordinates;let d="";
 for(const poly of polys)for(const ring of poly){ if(!ring.some(([lo,la])=>lo>lon0-3&&lo<lon1+3&&la>lat0-3&&la<lat1+3))continue;
  let prev="";ring.forEach((pt,i)=>{const [x,y]=P(pt);const s=`${x},${y}`;if(s===prev)return;d+=(i?"L":"M")+s;prev=s;});d+="Z";}
 return d;};
const want={"398":"kz","643":"ru","156":"cn","860":"uz","417":"kg","795":"tm","496":"mn","762":"tj"};
const out={W,H,lon0,lat1,k,sx,shapes:{}};
for(const f of fc.features){const c=want[f.id];if(!c)continue;const d=path(f.geometry);if(d)out.shapes[c]=d;}
const data={W,H,lon0,lat1,k:+k.toFixed(6),sx:+sx.toFixed(6),shapes:out.shapes};
require("fs").writeFileSync(require("path").join(__dirname,"..","dist","map-data.js"),
  "\"use strict\";\n// Generated by tools/map.js from Natural Earth 1:50m (world-atlas). Simplified study map.\nwindow.DALA_MAP="+JSON.stringify(data)+";\n");
console.log("map-data.js written");
